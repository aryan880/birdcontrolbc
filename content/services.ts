export function getServiceBySlug(slug: string) {
  return services.find((service) => service.slug === slug);
}

export function getPublishedServices() {
  return services.filter((service) => service.routeEnabled && service.routeHref);
}

export function getServiceHref(service: Service) {
  return service.routeHref ?? service.href;
}

export function getServicesBySlugs(slugs: string[]) {
  return slugs
    .map((slug) => getServiceBySlug(slug))
    .filter((service): service is Service => Boolean(service));
}
